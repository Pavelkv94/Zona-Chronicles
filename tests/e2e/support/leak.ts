/**
 * Проверка «этого зритель не видит» — на СНИМКЕ текста, а не ожиданием исчезновения.
 *
 * ## Почему `not.toContainText` здесь мёртв
 *
 * Негативное web-first утверждение Playwright ПОВТОРЯЕТСЯ, пока текст не исчезнет, и зеленеет в
 * тот момент, когда его не стало. Лента же ограничена сверху (`FEED_LIMIT = 40`), а при темпе
 * сценария 600 мировых минут за реальную секунду строка вымывается из неё быстрее дефолтного
 * пятисекундного таймаута. Утечка в ленте не отлавливалась вовсе: проверка дожидалась прокрутки.
 *
 * Найдено независимым test-review I04-I06 (B1) мутацией «`уйти отсюда` → `уйти отсюда, здесь
 * опасно`»: слово об опасности стояло на экране, и все восемь проверок утечки прошли.
 *
 * Моя собственная проба того же места «сработала» и подтвердила ложное — я вставлял слово в
 * заголовок карты, то есть в НЕпрокручиваемый элемент, который держится вечно. Детектор мерил
 * не то, что я думал: не «утечки нет», а «утечка не в шапке».
 *
 * ## Что вместо
 *
 * Текст снимается ОДНИМ вызовом в тот момент, когда утечка была бы видна, и проверяется обычным
 * строковым `expect` — без повторов, без таймаутов, без зависимости от прокрутки.
 */
import { expect, type Page } from '@playwright/test';

/**
 * Слова, которые могли бы прийти ТОЛЬКО из канона или из разбора оценок.
 *
 * Слова `risk` в списке нет намеренно: `risk.observed` — законный тип факта, и лента печатает
 * его дословно (`tests/integration/i03-projection-builder.test.ts` признаёт это прямо). Запрет
 * на само слово поставил бы e2e в противоречие с integration-тестом об одном и том же экране —
 * и был бы зелёным только по таймингу, чем и оказался.
 */
export const CANONICAL_LEAK_WORDS: readonly string[] = [
  'caution',
  'осторожн',
  'опасн',
  'switching_cost',
  'urgency',
  'time_cost',
  'perceived',
];

/** Снимок всего видимого текста страницы в ЭТОТ момент. */
export async function visibleText(page: Page): Promise<string> {
  return page.locator('body').innerText();
}

/**
 * Ни одно из запретных слов не стоит на экране в момент снимка.
 *
 * `where` попадает в сообщение об ошибке: снимков в сценарии несколько, и «утечка» без указания
 * момента заставила бы искать её перебором.
 */
export function expectNoCanonicalLeak(text: string, where: string): void {
  const lower = text.toLowerCase();
  for (const word of CANONICAL_LEAK_WORDS) {
    expect(
      lower,
      `${where}: на экране слово «${word}», которое приходит только из канона`,
    ).not.toContain(word.toLowerCase());
  }
}
