/**
 * I04 — цикл нужды виден в браузере БЕЗ вмешательства оператора (PLAN §2, §7).
 *
 * Отличие от D13 в одном, и оно принципиальное: там путь начинала команда человека, здесь мир
 * действует сам. Ни одного `world run` в сценарии нет — голод наступает от течения времени,
 * решение поесть принимает мир по достигнутому порогу, и всё это зритель видит на экране.
 *
 * Проверяется именно то, ради чего итерация затевалась: «ресурсы и тело создают реальную
 * необходимость действовать», и необходимость эта НАБЛЮДАЕМА, а не спрятана в состоянии.
 */
import { expect, test } from '@playwright/test';
import { startWorldStack, type WorldStack } from './support/world-stack.ts';

let stack: WorldStack;

/**
 * Темп 600 минут мира за реальную секунду.
 *
 * Голод доходит до предела за 18 мировых часов (коэффициенты ruleset), то есть за ~1.8 реальной
 * секунды при этом темпе. При темпе D13 (6) тот же путь занял бы три часа реального времени —
 * сценарий, который нельзя прогнать, не проверяет ничего.
 *
 * На ЧТО произойдёт, темп не влияет вовсе (D2): он меняет только «когда».
 */
test.beforeAll(async () => {
  stack = await startWorldStack('hunger', { worldMinutesPerRealSecond: 600 });
});

test.afterAll(async () => {
  await stack.stop();
});

test('голод наступает, агент ест, и зритель видит оба события без единой команды', async ({
  page,
}) => {
  await page.goto(stack.webUrl);

  // Место ищется в ЗАГОЛОВКЕ узла, а не в любом тексте страницы: с I06-D карта называет дороги
  // именами мест, и «Тихий двор» встречается на экране пять раз. Утверждение при этом стало
  // точнее — двор есть на карте как МЕСТО, а не просто упомянут где-то.
  await expect(page.locator('.node-name', { hasText: 'Тихий двор' })).toBeVisible();
  await expect(page.getByText('Поток: живой')).toBeVisible();

  // Мир начинается сытым: у карточки виден запас, а не жалоба.
  await expect(page.getByText('еды: 2').first()).toBeVisible();

  // Первое, что делает время, — портит самочувствие. Усталость наступает раньше голода.
  await expect(page.getByText(/устал/).first()).toBeVisible({ timeout: 30_000 });

  // Мир сам решает поесть, и это ВИДНО как решение, а не только как результат: с I05-B еду
  // назначает не порог, а выбор агента, и лента показывает выбор отдельной строкой.
  await expect(page.getByText(/решил поесть/).first()).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText(/поел/).first()).toBeVisible({ timeout: 30_000 });

  // Всё увиденное — следствие фактов, а не рисунка на экране: то же событие лежит в ленте.
  // Проверяется ЗДЕСЬ, а не в конце сценария: лента показывает последние сорок событий, а с
  // I05-B мир производит их заметно гуще — к концу прогона еда уходит за край окна, и проверка
  // в конце падала бы не потому, что мир её не произвёл.
  await expect(page.locator('.feed')).toContainText('поел');

  // Запас израсходован: после двух приёмов пищи на карточке не остаётся еды.
  await expect(page.getByText('еды нет').first()).toBeVisible({ timeout: 60_000 });

  // И тогда голод остаётся: мир не кормит агента из ниоткуда.
  await expect(page.getByText(/изголодался/).first()).toBeVisible({ timeout: 60_000 });

  // Разбора оценок на экране НЕТ и быть не может: §7 `03_TECHNICAL_DESIGN` запрещает публичному
  // слою decision trace. Проверяется отсутствием слов, которые могли бы прийти только оттуда.
  await expect(page.locator('body')).not.toContainText('switching_cost');
  await expect(page.locator('body')).not.toContainText('urgency');
});
