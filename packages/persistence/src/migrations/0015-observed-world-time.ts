/**
 * 0015 — «который час в мире» становится общим знанием, а не внутренним состоянием worker-а
 * (I04, возврат дефекта кредита темпа из I03).
 *
 * ## Какой дефект это чинит
 *
 * Мировое время двигают только события (ADR-004), поэтому в тишине оно стоит. Горизонт — до
 * какого момента миру РАЗРЕШЕНО дойти — при этом растёт от реального времени, и разрыв между
 * ними это нормально: без него действие, назначенное на будущее, не наступило бы никогда.
 *
 * Пока мир бывал по-настоящему пустым, worker переставлял точку отсчёта, и разрыв не копился
 * (починка I03). Нужды это состояние отменили: у мира ВСЕГДА есть ждущее действие — следующий
 * порог голода, — поэтому отсчёт больше не переставляется, и разрыв растёт всё время простоя.
 *
 * Сам по себе разрыв безвреден. Ломается другое: внешняя команда штампуется ТЕКУЩИМ мировым
 * временем, то есть моментом последнего события, который уже далеко позади горизонта. Путь,
 * начатый «сейчас», получает время прибытия в прошлом относительно горизонта и завершается на
 * первом же шаге. Измерено: сорокаминутный путь занимал 0.7 реальной секунды вместо десяти.
 *
 * ## Почему колонка, а не вычисление на месте
 *
 * Горизонт знал только процесс worker-а, у которого он живёт в памяти. CLI, исполняющий внешнюю
 * команду, — другой процесс, и вывести горизонт ему неоткуда. Колонка делает «который час в
 * мире» общим знанием ровно тех, кому оно нужно, и не требует второй арифметики темпа, способной
 * разойтись с первой.
 *
 * ## Почему это НЕ каноническое поле
 *
 * `observed_world_time` не входит ни в `WorldState`, ни в checksum снимка, ни в replay: это
 * операционная отметка «докуда мир дошёл по разрешению», как `lease_until` у расписания. Replay
 * по-прежнему считает состояние из событий, а каждое событие несёт своё `world_time`.
 *
 * Колонка допускает `null` — мир, у которого шага ещё не было. Читатель обязан тогда честно
 * взять текущее мировое время, а не подставить догадку.
 */
