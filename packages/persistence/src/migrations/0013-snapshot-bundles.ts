/**
 * 0013 — снимок записывает bundles, под которыми он снят (I03, M6 независимого аудита).
 *
 * ## Какой дефект это чинит
 *
 * `world_snapshots` намеренно не хранила bundles: они входят в `Snapshot.checksum`, поэтому
 * подделать строку, не сломав checksum, невозможно, и хранение выглядело избыточным. Довод верен
 * ровно наполовину — он про ЗАЩИТУ и ничего не говорит про ДИАГНОСТИКУ.
 *
 * Следствие обнаружил независимый аудит. Смена версии контента (в этой же итерации 0.1.0 → 0.2.0)
 * меняет checksum bundle. Читающая сторона передаёт ТЕКУЩИЕ bundles, checksum не сходится, и мир
 * получает отказ «снимок невосполним — расхождение обязано быть сбоем, а не тихо другим миром».
 * Формально верно, по смыслу — обвинение не по адресу: мир цел, изменился контент. Хуже того,
 * `world replay` печатал «нарушение SIM-01», то есть детектор детерминизма обвинял детерминизм в
 * том, что сделала правка контента, а оператор шёл искать несуществующую поломку.
 *
 * ## Почему колонка, а не догадка
 *
 * Различить «мир испорчен» и «bundle изменился» по одной строке нельзя в принципе: не с чем
 * сравнивать. Единственный способ — записать, ПОД КАКИМИ bundles снимок снят, и сравнить их
 * ПЕРВЫМИ, до checksum. Тогда у двух разных бед два разных сообщения и два разных выхода.
 *
 * Колонка допускает `null` — снимки, снятые до этой миграции. Для них поведение прежнее:
 * различить нечем, и отказ остаётся общим. Backfill невозможен и не имитируется: bundles нигде
 * не записаны, а придумать их значит подтвердить непроверенное.
 */
