import type { GoalKind, ItemKind, NeedKind, NeedLevel } from '@zona/contracts';

/**
 * Внутреннее (canonical) состояние мира — первый slice (§11 `09_EVENT_AND_COMMAND_CONTRACTS`):
 * агенты и маршруты, достаточные для `journey.start` → `journey.started`.
 *
 * Форму владеет домен (`snapshot.ts` контракта: «форма принадлежит домену, контракт требует
 * лишь того, чтобы оно было канонически сериализуемым»). Поэтому состояние — простые объекты,
 * массивы и примитивы, БЕЗ `Map`/`Set`: `canonicalize` из `@zona/contracts` отвергает их как
 * «не имеющие канонического представления», а `WorldState` должен без преобразований стать
 * `Snapshot.canonical_state`.
 *
 * Ключи `agents`/`routes` — сами id (`agent:*`, `route:*`): порядок вставки не несёт смысла и
 * не влияет на checksum, потому что `canonicalize` сортирует ключи по кодовым точкам (SIM-01).
 */

/**
 * Что агент делает прямо сейчас. `resting` добавлен в I05: отдых занял мировое время, и агент
 * во время него ЗАНЯТ — значит, состояние обязано быть наблюдаемым, иначе «отдыхает» ничем не
 * отличалось бы от «стоит без дела», и прервать его было бы нечего.
 */
export type AgentStatus = 'idle' | 'traveling' | 'resting';

export interface AgentState {
  readonly id: string;
  readonly locationId: string;
  readonly status: AgentStatus;
  /** Маршрут, по которому агент сейчас идёт; `null`, а не отсутствующее поле, когда `idle`. */
  readonly routeId: string | null;
  /**
   * Момент мирового времени, с которого отсчитывается каждая нужда (I04, §5).
   *
   * Каноническим является ИМЕННО момент, а не значение нужды: значение вычисляется из него
   * чистой функцией (`needs.ts`) и потому не является фактом. Хранить оба означало бы держать
   * два источника одной истины, которые однажды разойдутся, — и разойдутся молча, потому что
   * несогласованность видна только при сравнении.
   */
  readonly needBaseline: Readonly<Record<NeedKind, string>>;
  /**
   * Цель, которой агент придерживается сейчас (I05, §6).
   *
   * Цель КОРОТКОЖИВУЩАЯ: она появляется решением и потребляется своим шагом. Отдохнувший агент
   * снова празден — не потому, что передумал, а потому, что цель достигнута, и держать её
   * дальше значило бы утверждать намерение, которого у агента больше нет.
   *
   * Из этого следует форма отказа при выборе (см. `decide`): неизменная НЕидлевая цель означает
   * не «агент остался при своём», а «шаг потерян», и решение обязано поставить шаг заново.
   */
  readonly goal: GoalKind;
  /**
   * Тождество текущего плана; `null`, когда плана нет (I05-C).
   *
   * План — сущность, а не подразумеваемое следствие цели, и это видно ровно в одном месте: когда
   * план СРЫВАЕТСЯ. Факт `plan.invalidated` обязан назвать, ЧТО именно сорвалось, иначе два
   * подряд сорванных плана одного агента неотличимы в летописи, и вопрос «этот план сорвался
   * дважды или сорвались два разных» остаётся без ответа.
   *
   * Идентификатор выводится из факта, породившего план (`planIdFor`), и потому детерминирован:
   * пересимуляция журнала восстанавливает его без отдельного механизма.
   */
  readonly planId: string | null;
  /**
   * Осторожность в тысячных: множитель, с которым воспринимаемый риск входит в цену дороги
   * (I06, §8 — `caution_weight`).
   *
   * Тысяча — нейтрально, больше — осторожнее. Разыгрывается в генезисе из seed и с этого момента
   * неизменна: черта характера не меняется от того, что человеку не повезло с дорогой.
   *
   * Разыгрывается, а НЕ задаётся контентом. «Одинаковые агенты при одном seed ведут себя
   * одинаково» — это требование объяснимости различий, а не требование их отсутствия: мир, где
   * все одинаково осторожны, гипотезу итерации проверить не может.
   */
  readonly caution: number;
  /**
   * Что агент знает об опасности дорог (I06, §12).
   *
   * Ключ — id дороги; отсутствие ключа означает «не знает», а не «считает безопасной». Разница
   * решающая: неизвестное имеет ЦЕНУ, а не значение по умолчанию, и подставить сюда ноль
   * значило бы сделать весь мир заведомо безопасным для того, кто ничего не видел.
   *
   * Знание — субъективное. Совпадение с каноном не гарантируется и не проверяется: расхождение
   * между тем, что есть, и тем, что агент думает, — это и есть предмет итерации, а не дефект.
   */
  readonly knownRoutes: Readonly<Record<string, RouteKnowledge>>;
}

/**
 * Одна запись субъективной карты риска.
 *
 * Provenance обязателен (SIM-05): у знания есть источник и момент. Источником здесь всегда
 * является факт `risk.observed` — его `event_id` и хранится. Когда появятся пересказ и вывод,
 * источником станет их факт, и форма записи не изменится.
 */
export interface RouteKnowledge {
  readonly risk: number;
  /** Момент мирового времени, когда узнал. */
  readonly at: string;
  /** `event_id` факта, из которого знание получено. Провенанс, а не украшение. */
  readonly sourceEventId: string;
}

/**
 * Предмет мира (I04).
 *
 * Владелец РОВНО один и всегда назван: агент. Лежащих на земле предметов в этой итерации нет —
 * их появление означало бы второй способ владения и второй набор правил передачи, а передачи
 * ещё нет вовсе. Когда предметы начнут лежать в локациях (I08), поле станет union-ом, и это
 * заставит разобрать оба случая явно, а не добавит `null`, который потребитель забудет проверить.
 */
export interface ItemState {
  readonly id: string;
  readonly kind: ItemKind;
  readonly ownerId: string;
}

export interface RouteDefinition {
  readonly id: string;
  readonly fromLocationId: string;
  readonly toLocationId: string;
  /** Время в пути; единица — минуты мирового времени (`addMinutes` контракта). */
  readonly travelMinutes: number;
  /**
   * Опасность дороги в тысячных (I06, §8).
   *
   * КАНОНИЧЕСКАЯ величина — то, как опасно на самом деле. Агент её не знает и знать не обязан:
   * решение принимается по субъективной карте, а не отсюда. Прочитать это поле при выборе дороги
   * — и есть тот самый утёк, который итерация объявила STOP-условием, поэтому выбор считается от
   * СИТУАЦИИ, куда канон не попадает вовсе.
   */
  readonly risk: number;
}

/**
 * Место мира (I06).
 *
 * До этой итерации локации жили только в контенте и в проекции: домену от них ничего не было
 * нужно — агент помнил свой `locationId`, и этого хватало. С появлением опасности место стало
 * иметь свойство, от которого зависит решение, и потому вошло в каноническое состояние.
 */
export interface LocationState {
  readonly id: string;
  /** Опасность места в тысячных. Агент, находящийся здесь, знает её без всякой памяти. */
  readonly risk: number;
}

/**
 * Запланированное действие — ЧАСТЬ канонического состояния, а не операционная очередь (I02B).
 *
 * Это решение, и оно неочевидное. Альтернатива — таблица задач, которую наполняет адаптер
 * персистентности, прочитав `expected_arrival` из события. Она короче, но переносит доменное
 * знание («начатый путь обязан завершиться») в оболочку, и тогда replay журнала перестаёт
 * восстанавливать расписание: его пришлось бы восстанавливать отдельным механизмом, который
 * может разойтись с событиями молча.
 *
 * Здесь расписание выводится из событий чистой функцией `evolve`, поэтому пересимуляция
 * восстанавливает его бесплатно и по построению не может разойтись с историей. Таблица в БД —
 * зеркало этого состояния плюс операционные поля аренды, которые каноническими не являются и в
 * checksum не входят.
 *
 * `id` детерминирован и уникален; ЧЕМ именно он является, решает вид действия. У завершения
 * пути это `event_id` события-причины — связь прямая, без отдельного справочника. У пересечения
 * порога нужды события-причины может не быть вовсе (первое пересечение планируется в генезисе),
 * поэтому там ключ собирается из агента, нужды и момента. Общее требование одно: по ключу
 * действие должно быть отличимо от любого другого, включая уже выполненные.
 */
interface ScheduledActionBase {
  readonly id: string;
  /** Каноническая ISO-метка МИРОВОГО времени, когда действие становится доступным. */
  readonly dueAt: string;
  /** Меньше — раньше. Разводит действия с одинаковым `dueAt` до сравнения id (C4). */
  readonly priority: number;
  readonly entityId: string;
}

/**
 * Завершение начатого пути. `id` равен `event_id` события-причины: связь «действие ↔ факт, его
 * породивший» прямая, без отдельного справочника, и `journey.completed` снимает действие именно
 * по ней (M7).
 */
export interface JourneyCompleteAction extends ScheduledActionBase {
  readonly kind: 'journey.complete';
  readonly routeId: string;
}

/**
 * Пересечение порога нужды (I04).
 *
 * `id` НЕ равен id события-причины, и это вынужденно: самое первое пересечение планируется в
 * генезисе, где событий нет вовсе. Ключ вместо этого детерминирован —
 * `sched:need:<агент>:<нужда>:<момент>`, — и уникален по построению: у одного агента по одной
 * нужде не может быть двух ждущих пересечений одновременно.
 *
 * Это не «совпадение полей», от которого предостерегает M7: там пара «агент + маршрут» была
 * ЭВРИСТИКОЙ, верной лишь пока механика одна. Здесь ключ содержит момент срабатывания, поэтому
 * различает даже два пересечения одной нужды у одного агента.
 */
/**
 * Съесть предмет — ШАГ выбранной цели «поесть» (I04 → I05).
 *
 * В I04 это действие планировалось безальтернативным правилом «дошёл до предела голода и еда
 * есть — ест». В I05 правило заменено ВЫБОРОМ: шаг ставится следствием факта `goal.chosen`, а не
 * следствием порога. Двух механизмов, планирующих еду, в мире нет и быть не должно — разойдясь,
 * они дали бы агента, который ест по одной причине и не ест по другой.
 */
export interface AgentEatAction extends ScheduledActionBase {
  readonly kind: 'agent.eat';
  readonly itemId: string;
}

/** Завершение начатого отдыха (I05). `id` равен `event_id` события `rest.started`. */
export interface RestCompleteAction extends ScheduledActionBase {
  readonly kind: 'rest.complete';
}

/**
 * Выбор цели (I05, §6).
 *
 * Планируется, когда для агента что-то ИЗМЕНИЛОСЬ и он при этом свободен (§4.2 плана I05).
 * Периодического опроса нет намеренно: «каждые N минут пересчитать цели» — это pulse под другим
 * именем, со всей ценой, из-за которой §5 спецификации пришлось переписать в I04.
 *
 * `id` собирается из агента и момента, а не равен `event_id` причины: решений в один момент у
 * одного агента не может быть двух, а причин, порождающих решение, несколько — привязка к одной
 * из них потребовала бы отдельного справочника «какая причина к какому решению».
 */
export interface AgentDecideAction extends ScheduledActionBase {
  readonly kind: 'agent.decide';
}

/**
 * Шаг цели «отдохнуть»: лечь отдыхать (I05).
 *
 * Отдельное действие, а не немедленное исполнение внутри `evolve`: у мира один способ
 * измениться, и шаг выбранной цели проходит через `decide` со своими предусловиями — ровно как
 * приём пищи и завершение пути.
 */
export interface AgentRestAction extends ScheduledActionBase {
  readonly kind: 'agent.rest';
}

export interface NeedThresholdAction extends ScheduledActionBase {
  readonly kind: 'need.threshold';
  readonly need: NeedKind;
  /** Уровень, которого нужда достигнет к `dueAt`. Ожидание, которое `decide` перепроверяет. */
  readonly toLevel: NeedLevel;
}

export type ScheduledAction =
  | JourneyCompleteAction
  | NeedThresholdAction
  | AgentEatAction
  | RestCompleteAction
  | AgentDecideAction
  | AgentRestAction;

/**
 * Ключи действий, порождённых ФАКТОМ, выводятся из `event_id` этого факта.
 *
 * Так было не всегда: до I05 ключ приёма пищи собирался из агента и момента. Ключ, собранный из
 * момента, уникален ровно до тех пор, пока одно и то же действие не может быть назначено агенту
 * дважды в один момент мирового времени, — а с появлением выбора это перестало быть верным.
 * Цепочка «поел → освободился → решил → …» целиком укладывается в один момент, потому что ни
 * решение, ни приём пищи мирового времени не занимают. Ключ по моменту дал бы повторную вставку
 * строки с уже существующим первичным ключом, то есть падение записи транзакции, — и только в
 * той ветке, где мир успел сделать два шага подряд.
 *
 * `event_id` уникален по построению и уже несёт причинность. Снимаются такие действия НЕ по
 * ключу (команда, выведенная из расписания, не знает id своей причины), а по признаку самого
 * действия — см. `evolve`.
 */
export function agentDecideActionId(causeEventId: string): string {
  return `sched:decide:${causeEventId}`;
}

/** Детерминированный ключ шага «лечь отдыхать». */
export function agentRestActionId(causeEventId: string): string {
  return `sched:rest:${causeEventId}`;
}

/** Детерминированный ключ шага «поесть». */
export function agentEatActionId(causeEventId: string): string {
  return `sched:eat:${causeEventId}`;
}

/**
 * Тождество плана: `plan:<агент>-<цель>-<sequence решения>`.
 *
 * Выводится из факта `goal.chosen`, а не из его `event_id`, по требованию схемы: `plan_id` в
 * payload — namespaced id (`строчные буквы, цифры и дефисы`), а runtime id события написан
 * заглавными и с подчёркиванием. Номер решения делает ключ уникальным во времени: два
 * последовательных плана «поесть» у одного агента получают разные тождества, и «сорвался дважды»
 * перестаёт быть неотличимым от «сорвались два разных».
 */
export function planIdFor(agentId: string, goal: GoalKind, sequence: number): string {
  const local = agentId.includes(':') ? (agentId.split(':')[1] ?? agentId) : agentId;
  return `plan:${local}-${goal}-${String(sequence)}`;
}

/** Детерминированный ключ действия по нужде. Один источник формата на весь проект. */
export function needThresholdActionId(agentId: string, need: NeedKind, dueAt: string): string {
  return `sched:need:${agentId}:${need}:${dueAt}`;
}

