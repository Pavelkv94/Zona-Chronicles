/**
 * Свободен ли агент — то есть может ли он прямо сейчас принимать решение (§4.2 плана I05).
 *
 * Свобода выражена ДВУМЯ полями состояния агента и не смотрит в расписание вовсе. Это решение,
 * и оно неочевидное: естественнее было бы спросить «нет ли у него ждущего действия». Но
 * действие, отвергнутое доменом, остаётся в расписании навсегда (у отказа нет события, а
 * расписание выводится только из событий), и агент, чей шаг однажды был отвергнут, перестал бы
 * считаться свободным до конца существования мира. Молча.
 *
 * Цель и статус такого свойства не имеют: цель ставится и снимается только фактами.
 *
 * `idle` в обоих полях означает разное и проверяется поэтому дважды: статус — что агент не занят
 * действием, занимающим мировое время; цель — что у него нет уже принятого намерения, шаг
 * которого ещё не исполнен. Новое решение при непустой цели отменило бы её молча.
 */
export function isAgentFree(agent: AgentState): boolean {
  return agent.status === 'idle' && agent.goal === 'idle';
}

export interface WorldState {
  readonly worldId: string;
  /** Версия мира для optimistic concurrency (`expected_world_version` команды, §2). */
  readonly worldVersion: number;
  /** Каноническая ISO-метка мирового времени на момент этого состояния. */
  readonly worldTime: string;
  /** Последняя применённая sequence; 0 — мир без событий (`SNAPSHOT_SEQUENCE_UNIT`). */
  readonly sequence: number;
  readonly agents: Readonly<Record<string, AgentState>>;
  readonly locations: Readonly<Record<string, LocationState>>;
  readonly routes: Readonly<Record<string, RouteDefinition>>;
  /** Ключ — `id` предмета. Предмет существует, пока он здесь; сток его отсюда убирает. */
  readonly items: Readonly<Record<string, ItemState>>;
  /** Ключ — `id` действия. Порядок вставки смысла не несёт: `canonicalize` сортирует ключи. */
  readonly scheduledActions: Readonly<Record<string, ScheduledAction>>;
}
