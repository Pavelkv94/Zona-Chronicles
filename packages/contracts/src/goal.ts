/**
 * Цели агента и разбор решения (I05, `07_MVP_MECHANICS_SPEC` §6).
 *
 * Здесь ТОЛЬКО словарь и формы. Ни весов, ни порога смены цели: коэффициенты живут в versioned
 * ruleset и приходят в домен портом `Ruleset` (ADR-003) — по тому же основанию, по которому
 * пороги нужд не попали в `need.ts`. Контракт, содержащий число 400, сделал бы срочность частью
 * схемы, то есть неизменяемой без правки контракта.
 *
 * ## Почему целей три, а §6 перечисляет двенадцать
 *
 * Цель, для которой в мире нет ни одного исполнимого шага, — это не цель с низкой оценкой, а
 * цель без адресата. «Пополнить ресурсы» требует источника предметов (I08), «помочь союзнику» —
 * отношений (I09), «избежать угрозы» — угроз (I07). Завести их сейчас значило бы получить
 * кандидатов, которые НИКОГДА не выигрывают, и объяснение выбора, в котором половина строк
 * ничего не объясняет.
 */
import { type Static, Type } from '@sinclair/typebox';

/**
 * Кандидатные цели, В ПОРЯДКЕ ОБЪЯВЛЕНИЯ.
 *
 * `flee` дописан в конец (I06-C), а не вставлен по смыслу: порядок задаёт разрешение ничьей, и
 * перестановка существующих целей молча изменила бы поведение всех прежних миров.
 *
 * Порядок значим дважды. Он задаёт детерминированный tie-break: при равных оценках выигрывает
 * объявленная раньше. И он ставит `idle` первым намеренно — при равенстве мир предпочитает
 * ничего не делать. Сомнение решается в пользу бездействия, а не суеты: цель, которая не лучше
 * безделья, не стоит потраченного мирового времени.
 */
export const GOAL_KINDS = ['idle', 'eat', 'rest', 'flee'] as const;

export type GoalKind = (typeof GOAL_KINDS)[number];

export const GoalKindSchema = Type.Union(
  GOAL_KINDS.map((kind) => Type.Literal(kind)),
  { description: 'Цель агента (07_MVP_MECHANICS_SPEC §6, первый срез I05).' },
);

/** Порядковый номер цели в объявленном порядке. Tie-break без знания имён. */
export function goalRank(goal: GoalKind): number {
  return GOAL_KINDS.indexOf(goal);
}

/**
 * Одна строка разбора решения: цель, её слагаемые и итог.
 *
 * Слагаемые названы по §6 и записаны ЦЕЛЫМИ в тысячных (`GOAL_SCORE_UNIT`): каноническая
 * сериализация отвергает дробное число, и это не формальность — дробь в JSON зависит от
 * платформы округления, а разбор решения входит в канонический факт и участвует в checksum.
 *
 * `feasible` присутствует у КАЖДОЙ цели, а не только у выигравшей, и неисполнимые цели из
 * разбора не выбрасываются. Разбор, содержащий только кандидатов, не может ответить на главный
 * вопрос расследования — «почему НЕ поел», — и отличить «не было еды» от «еда была, но отдых
 * оказался важнее» стало бы невозможно.
 *
 * Слагаемые считаются и для неисполнимых целей: иначе поля пришлось бы сделать nullable, и
 * каждый потребитель разбора получил бы второй случай, который однажды забудет разобрать.
 */
export const GoalScoreLineSchema = Type.Object(
  {
    goal: GoalKindSchema,
    feasible: Type.Boolean({
      description: 'Есть ли исполнимый первый шаг ЗДЕСЬ И СЕЙЧАС; неисполнимая цель не выбирается.',
    }),
    urgency: Type.Integer({ description: 'Срочность нужды цели, тысячные (§6).' }),
    time_cost: Type.Integer({ description: 'Цена мирового времени, тысячные (§6).' }),
    switching_cost: Type.Integer({ description: 'Цена ухода от текущей цели, тысячные (§6).' }),
    score: Type.Integer({ description: 'urgency - time_cost - switching_cost, тысячные.' }),
  },
  { $id: 'zona:goal-score-line/1', additionalProperties: false },
);

/**
 * Разбор решения (`decision trace` §6): debug-data, а не публичная цепочка рассуждений.
 *
 * Живёт в каноническом журнале и НЕ входит в observer-контракт (ADR-005, §7
 * `03_TECHNICAL_DESIGN` прямо запрещает публичному snapshot отдавать decision trace). Зрителю
 * показывается факт «решил поесть», а не таблица оценок.
 *
 * Свободного текста здесь нет: объяснение, написанное словами рядом с числами, однажды с ними
 * разойдётся, и разойдётся молча — сверить их будет нечем.
 *
 * Строк ровно столько, сколько целей в `GOAL_KINDS`, и в том же порядке. Полнота проверяется
 * contract-тестом: разбор, из которого выпала цель, — это разбор, скрывающий альтернативу.
 */
export const DecisionTraceSchema = Type.Object(
  {
    candidates: Type.Array(GoalScoreLineSchema, {
      minItems: 1,
      description: 'Все цели в объявленном порядке, включая неисполнимые.',
    }),
  },
  { $id: 'zona:decision-trace/1', additionalProperties: false },
);

export type GoalScoreLine = Static<typeof GoalScoreLineSchema>;
export type DecisionTrace = Static<typeof DecisionTraceSchema>;
