/**
 * Нужды тела: перечисления и примитивы схем (I04, `07_MVP_MECHANICS_SPEC` §5).
 *
 * Здесь ТОЛЬКО словарь и формы. Ни значений порогов, ни скорости роста: коэффициенты живут в
 * versioned ruleset и приходят в домен портом `Ruleset` (ADR-003). Контракт, содержащий число
 * 0.45, сделал бы порог частью схемы — то есть неизменяемым без правки контракта, — а §5
 * называет пороги «умолчаниями», то есть настройкой.
 *
 * ## Почему уровень, а не значение, попадает в события
 *
 * Значение нужды — производная величина: оно вычисляется из момента отсчёта, текущего мирового
 * времени и коэффициентов (§5, решение I04). Публиковать его в факте значило бы записывать
 * измерение, которое в следующий момент уже другое, и делать журнал выборкой измерений вместо
 * списка фактов. Фактом является ПЕРЕСЕЧЕНИЕ порога — оно происходит один раз и остаётся
 * истинным навсегда.
 */
import { Type } from '@sinclair/typebox';

/**
 * Виды нужд первого среза I04. Стресс, мораль и здоровье сюда НЕ входят: §5 их описывает, но
 * правила тела и морали — это I06/I07, а схема, заведённая заранее, замораживает решение,
 * которое ещё не принято (§12 контрактов).
 */
export const NEED_KINDS = ['hunger', 'fatigue'] as const;

export type NeedKind = (typeof NEED_KINDS)[number];

/**
 * Уровни нужды в порядке УХУДШЕНИЯ. Порядок значим: по нему определяется направление перехода
 * («ухудшение» или «восстановление») без отдельного поля в payload.
 */
export const NEED_LEVELS = ['normal', 'warning', 'critical'] as const;

export type NeedLevel = (typeof NEED_LEVELS)[number];

export const NeedKindSchema = Type.Union(
  NEED_KINDS.map((kind) => Type.Literal(kind)),
  { description: 'Вид нужды тела (07_MVP_MECHANICS_SPEC §5).' },
);

export const NeedLevelSchema = Type.Union(
  NEED_LEVELS.map((level) => Type.Literal(level)),
  { description: 'Уровень нужды: normal < 0.45 <= warning < 0.75 <= critical (§5).' },
);

/** Порядковый номер уровня; больше — хуже. Сравнение уровней без знания их имён. */
export function needLevelRank(level: NeedLevel): number {
  return NEED_LEVELS.indexOf(level);
}
