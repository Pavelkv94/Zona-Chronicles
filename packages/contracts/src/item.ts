/**
 * Предметы мира: словарь видов и примитивы схем (I04, `07_MVP_MECHANICS_SPEC` §2, §16).
 *
 * Здесь ТОЛЬКО словарь. Ни количеств, ни цен, ни веса: экономика — I08, и схема, заведённая
 * заранее, заморозила бы решение, которое ещё не принято (§12 контрактов).
 *
 * ## Почему предмет — сущность, а не число в инвентаре
 *
 * Счётчик «еды: 3» невозможно ни отследить, ни передать: у него нет истории и нет владельца,
 * которого можно назвать. SIM-07 требует, чтобы уникальные предметы не дублировались, а
 * проверить это можно только когда у предмета есть тождество. Расход четырёх взаимозаменяемых
 * банок при этом выражается четырьмя предметами — дороже в хранении, но честно в учёте.
 */
import { Type } from '@sinclair/typebox';

/**
 * Виды предметов первого среза. Медицина, боеприпасы и универсальный товар (§2) сюда НЕ входят:
 * их расходуют механики, которых ещё нет, и вид без механики — это словарь без смысла.
 */
export const ITEM_KINDS = ['food'] as const;

export type ItemKind = (typeof ITEM_KINDS)[number];

export const ItemKindSchema = Type.Union(
  ITEM_KINDS.map((kind) => Type.Literal(kind)),
  { description: 'Вид предмета (07_MVP_MECHANICS_SPEC §2).' },
);
