/**
 * Темп мира: сколько минут МИРОВОГО времени проходит за секунду реального (I03, D1/D2).
 *
 * Решение владельца (2026-08-22): горизонт задаёт скорость мира, наблюдатель на развитие мира не
 * влияет. Здесь это выражено буквально — горизонт вычисляется из прошедшего РЕАЛЬНОГО времени и
 * коэффициента, и ни один вход этой функции не зависит от действий зрителя.
 *
 * ## Где живёт коэффициент и почему НЕ в rules bundle
 *
 * `PLAN.md` §4.1 этой итерации говорил «коэффициент — в versioned ruleset». Сделано иначе, и это
 * отклонение записано в `PLAN.md` §10.
 *
 * Rules bundle адресуется checksum-ом и входит в канонический снимок: он доказывает, ПОД КАКИМИ
 * правилами посчитан мир. Темп на канонический результат не влияет вовсе (D2), поэтому его
 * включение связало бы снимки с параметром, который к ним не относится: изменение скорости
 * показа меняло бы checksum bundle, и снимки, снятые до правки, объявлялись бы несовместимыми.
 * Мир перестал бы восстанавливаться из-за поворота ручки темпа.
 *
 * Это тот же довод, по которому observer-схемы не входят в schema bundle (`observer.ts`), и
 * решать его двумя разными способами в одной итерации было бы непоследовательно.
 *
 * Поэтому коэффициент — версионированные ДАННЫЕ рядом с worker-ом: значение по умолчанию видно
 * в коде, у него есть собственная версия, и оно не является ни магической константой в глубине
 * цикла, ни невидимой переменной окружения.
 *
 * ## Что темп НЕ меняет
 *
 * Ни одно событие. `runWorldTick` продвигает мировое время к `due_at` обработанного действия, а
 * не к горизонту, поэтому горизонт решает лишь, СКОЛЬКО действий созрело к этому моменту. Порядок
 * обработки при равном `due_at` задан `(priority, entity_id, action_id)` и не зависит от размера
 * пачки (C4). Отсюда D1: журнал непрерывного хода обязан совпасть с журналом пошагового
 * `world tick --advance` на ту же длительность.
 */
import { addMinutes, isInstantError, parseInstant } from '@zona/contracts';

/** Версия темпа. Меняется вместе со значением по умолчанию — чтобы изменение было видно в diff. */
export const WORLD_TEMPO_VERSION = '1.0.0';

export interface WorldTempo {
  /** Минут мирового времени за секунду реального. Строго положительное конечное число. */
  readonly worldMinutesPerRealSecond: number;
}

/**
 * Значение по умолчанию: одна минута мира за секунду реального времени.
 *
 * Выбрано так, чтобы путь длиной 40 минут мира занимал 40 секунд наблюдения — достаточно быстро,
 * чтобы зритель увидел завершение, не уходя со страницы, и достаточно медленно, чтобы успеть
 * заметить сам переход. Это решение о ДЕМОНСТРАЦИИ, а не о мире: канонический журнал от него не
 * зависит (D2).
 */
export const DEFAULT_WORLD_TEMPO: WorldTempo = { worldMinutesPerRealSecond: 1 };

const MS_PER_SECOND = 1000;

export interface WorldHorizonInput {
  /** Мировое время в момент, от которого отсчитывается темп (старт worker-а). */
  readonly startWorldTime: string;
  /** Сколько РЕАЛЬНОГО времени прошло с этого момента. */
  readonly elapsedRealMs: number;
  readonly tempo: WorldTempo;
}

/**
 * До какого мирового времени миру разрешено дойти прямо сейчас.
 *
 * Дробная минута усекается ВНИЗ. Округление вверх выдало бы горизонт, которого реальное время
 * ещё не оплатило: мир на мгновение обгонял бы собственный темп, и «одна минута мира за секунду»
 * перестало бы быть правдой на границах.
 */
export function worldHorizon(input: WorldHorizonInput): string {
  const { worldMinutesPerRealSecond } = input.tempo;
  if (!Number.isFinite(worldMinutesPerRealSecond) || worldMinutesPerRealSecond <= 0) {
    throw new Error(
      `world-tempo: коэффициент скорости мира обязан быть конечным положительным числом, ` +
        `получено ${String(worldMinutesPerRealSecond)}. Остановившийся или пятящийся мир — это ` +
        'не темп, а поломка, и молчать о ней нельзя.',
    );
  }
  if (!Number.isFinite(input.elapsedRealMs) || input.elapsedRealMs < 0) {
    throw new Error(
      `world-tempo: прошедшее реальное время обязано быть конечным неотрицательным числом ` +
        `миллисекунд, получено ${String(input.elapsedRealMs)}.`,
    );
  }

  const start = parseInstant(input.startWorldTime);
  if (isInstantError(start)) {
    throw new Error(`world-tempo: стартовое мировое время невалидно: ${start.error}`);
  }

  const minutes = Math.floor((input.elapsedRealMs / MS_PER_SECOND) * worldMinutesPerRealSecond);
  const horizon = addMinutes(start, minutes);
  if (isInstantError(horizon)) {
    throw new Error(`world-tempo: горизонт невычислим: ${horizon.error}`);
  }
  return horizon.iso;
}
