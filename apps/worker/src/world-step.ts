/**
 * Шаг worker-а: довести мир до горизонта, вычисленного темпом (I03, D1).
 *
 * Это то место, где `apps/worker` перестаёт быть скелетом I00. До I03 `step` был честным no-op, и
 * трассировка PR-04 из-за этого утверждала больше доказанного (M8 аудита I02B): мир не шёл сам —
 * расписание разбирал `world tick`, который запускает оператор.
 *
 * `tick` инъектирован портом, а не импортирован здесь напрямую. Причина не в тестируемости как
 * таковой: без порта единственным способом проверить, КАКОЙ горизонт worker предъявляет миру,
 * была бы настоящая база и разбор её состояния постфактум — то есть проверка следствия вместо
 * проверки решения. Горизонт — единственное, что этот модуль решает; он и обязан быть наблюдаем.
 */
import { worldHorizon, type WorldTempo } from './world-tempo.ts';

/** Ровно та часть результата `runWorldTick`, которая нужна worker-у. */
export interface WorldTickOutcome {
  readonly claimed: number;
  readonly worldTime: string;
  /**
   * Срок ближайшего ждущего действия — или `null`, если миру нечего делать вовсе.
   *
   * Это не то же самое, что `claimed === 0`. Шаг захватывает ноль действий и когда мир пуст, и
   * когда действие запланировано, но ещё не созрело; для темпа это ПРОТИВОПОЛОЖНЫЕ состояния.
   * Различить их без этого поля нельзя, а починка, их спутавшая, останавливает мир насмерть
   * (проверено исполнением — см. докстринг `createWorldStep`).
   *
   * `undefined` — «неизвестно»: шаг не выполнялся, потому что мир в этот момент обрабатывал
   * другой worker. Неизвестность трактуется как «дело есть»: отсчёт не переставляется, потому
   * что его в этот момент ведёт тот, кто держит замок.
   */
  readonly nextDueAt?: string | null | undefined;
}

export interface WorldTickPort {
  (input: { readonly horizon: string }): Promise<WorldTickOutcome>;
}

export interface WorldStepDeps {
  /** Мировое время в момент старта worker-а: точка отсчёта темпа. */
  readonly startWorldTime: string;
  /** Реальные часы процесса в миллисекундах; инъектированы, чтобы шаг не зависел от wall clock. */
  readonly realNowMs: () => number;
  readonly tempo: WorldTempo;
  readonly tick: WorldTickPort;
  readonly logger?: {
    readonly info: (fields: Record<string, unknown>, msg: string) => void;
  };
}

/**
 * Точка отсчёта не догоняет пропущенное и не копит неизрасходованное.
 *
 * Догон пропущенного отвергнут сразу: мир, простоявший ночь, за один шаг проскочил бы восемь
 * часов, и зритель увидел бы не жизнь, а перемотку. Простой — это простой; мир продолжается с
 * того момента, где остановился.
 *
 * ## Кредит темпа, из-за которого одной точки отсчёта мало
 *
 * Точка, взятая единожды при старте, защищает только от простоя ДО запуска процесса. Простой ВО
 * ВРЕМЯ работы копился: мировое время двигают события (ADR-004), поэтому в тишине оно стоит, а
 * горизонт рос от реального. Разница — неизрасходованный кредит, и он тратился залпом на первое
 * же появившееся действие. Измерено: после 45 секунд тишины путь длиной сорок мировых минут
 * завершался за одну реальную секунду, а состояние «в пути» не существовало ни в один
 * наблюдаемый момент — на этом упал E2E-сценарий D13.
 *
 * Отвергнутая починка: привязать горизонт к ТЕКУЩЕМУ мировому времени на каждом шаге. Проверено
 * исполнением — мир встаёт совсем. Горизонт, привязанный к времени, которое двигают только
 * события, не дорастает до первого срока никогда: дробная минута усекается вниз, прибавка равна
 * нулю, и замкнутый круг ADR-004 возвращается целиком.
 *
 * Здесь третий вариант, и он опирается на различие, которого раньше не было в данных: «мир
 * ничего не захватил» и «миру нечего делать» — разные состояния. Отсчёт переставляется ТОЛЬКО
 * пока миру нечего делать, и замирает, как только появилось ждущее действие. Тупика нет:
 * замерев, отсчёт растёт как прежде и доводит горизонт до срока.
 *
 * Переустановка делается в начале СЛЕДУЮЩЕГО шага, а не в конце простаивающего. Разница в один
 * опрос, и она принципиальна по знаку: перенос в конец простоя выдал бы горизонт, оплаченный
 * временем, которое мир простоял, — путь завершался бы на опрос РАНЬШЕ срока. Мир, идущий
 * быстрее собственного темпа, — это тот же кредит, только маленький. Здесь остаётся лишь
 * задержка реакции: она ограничена интервалом опроса и не копится.
 *
 * Канонический журнал не меняется вовсе. Мировое время по-прежнему продвигается к `due_at`
 * обработанного действия, а не к горизонту, поэтому D2/SIM-01 — «темп не меняет мир» — этой
 * правкой не затронуты: меняется КОГДА зритель увидит переход, а не ЧТО произойдёт.
 */
export function createWorldStep(deps: WorldStepDeps): () => Promise<void> {
  let anchorRealMs = deps.realNowMs();
  let anchorWorldTime = deps.startWorldTime;
  let idleWorldTime: string | null = null;

  return async function step(): Promise<void> {
    const nowMs = deps.realNowMs();

    if (idleWorldTime !== null) {
      anchorRealMs = nowMs;
      anchorWorldTime = idleWorldTime;
      idleWorldTime = null;
    }

    const horizon = worldHorizon({
      startWorldTime: anchorWorldTime,
      elapsedRealMs: nowMs - anchorRealMs,
      tempo: deps.tempo,
    });

    const outcome = await deps.tick({ horizon });

    // Мир простоял этот шаг вхолостую — значит следующий начнётся с новой точки отсчёта, и
    // прошедшее время не превратится в кредит.
    if (outcome.nextDueAt === null) idleWorldTime = outcome.worldTime;

    // Логируется только шаг, что-то сделавший: цикл опрашивает мир чаще, чем мир меняется, и
    // строка «claimed: 0» в каждом опросе утопила бы настоящие события.
    if (outcome.claimed > 0) {
      deps.logger?.info(
        { horizon, claimed: outcome.claimed, worldTime: outcome.worldTime },
        'worker.world.advanced',
      );
    }
  };
}
