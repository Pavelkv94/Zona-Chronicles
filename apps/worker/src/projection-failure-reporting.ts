/**
 * Как часто жаловаться на подряд идущие отказы сборки проекции (I03).
 *
 * Отдельный модуль ради проверяемости: внутри `main.ts` эта функция была бы недостижима для
 * теста, а «счётчик, который только логируется» — ровно то, что нашёл независимый аудит.
 *
 * Правило: жалуемся на 1, 2, 4, 8-м отказе и дальше не реже, чем раз в сотню. Молчание после N
 * отказов было бы хуже шума — «перестало обновляться» это СОСТОЯНИЕ, и о нём положено напоминать,
 * пока оно длится. Полностью замолчать нельзя ни при каком числе отказов.
 */
export const shouldReportProjectionFailure = (consecutive: number): boolean =>
  consecutive <= 8
    ? (consecutive & (consecutive - 1)) === 0
    : consecutive % 100 === 0 || (consecutive & (consecutive - 1)) === 0;
